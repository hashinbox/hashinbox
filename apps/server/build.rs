//! Embeds every file the server serves: `ui/dist/` at the root and `assets/`
//! at `/assets/…`. Writes their `(url path, include_bytes!(file))` table
//! (`ui::FILES`), so a new file in either folder needs no code.
//!
//! Also regenerates the clients' models and operations (cligen) from the
//! committed `docs/openapi.json` into `clients/<language>/`, and sets
//! `HASHINBOX_VERSION`: the build environment's, else
//! `git describe --tags --always --dirty`, else the crate version.

use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
};

/// Every file under `folder`, recursively.
fn files(folder: &Path) -> Vec<PathBuf> {
    let Ok(entries) = fs::read_dir(folder) else {
        return Vec::new();
    };
    entries
        .map(|entry| entry.unwrap().path())
        .flat_map(|path| {
            if path.is_dir() {
                files(&path)
            } else {
                vec![path]
            }
        })
        .collect()
}

/// The version: `HASHINBOX_VERSION` if set, else the tag description of the
/// git checkout at or above `root`, else the crate version.
fn version(root: &Path) -> String {
    println!("cargo:rerun-if-env-changed=HASHINBOX_VERSION");
    if let Ok(version) = env::var("HASHINBOX_VERSION") {
        return version;
    }
    let crate_version = env::var("CARGO_PKG_VERSION").unwrap();
    let Some(git) = root
        .ancestors()
        .map(|dir| dir.join(".git"))
        .find(|git| git.exists())
    else {
        return crate_version;
    };
    for watched in ["HEAD", "refs"].map(|name| git.join(name)) {
        if watched.exists() {
            println!("cargo:rerun-if-changed={}", watched.display());
        }
    }
    let Ok(output) = Command::new("git")
        .args(["describe", "--tags", "--always", "--dirty"])
        .current_dir(git.parent().unwrap())
        .output()
    else {
        return crate_version;
    };
    let described = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    if !output.status.success() || described.is_empty() {
        return crate_version;
    }
    described
}

/// Writes cligen's files of `docs/openapi.json` into `clients/`: each
/// language's models and operations, each only when its text changed. An
/// older generated file (one starting with cligen's marker) that is no
/// longer written is deleted; every other file there is hand-written and
/// left alone. A document cligen refuses is a warning, the clients left as
/// they were.
fn clients(root: &Path) {
    let source = root.join("../../docs/openapi.json");
    println!("cargo:rerun-if-changed={}", source.display());
    let Ok(text) = fs::read_to_string(&source) else {
        return;
    };
    let spec = match cligen::Spec::from_openapi(&text) {
        Ok(spec) => spec,
        Err(error) => {
            println!("cargo:warning=docs/openapi.json: {error}; the clients are not regenerated");
            return;
        }
    };
    let go = cligen::go::Go {
        package: "hashinbox".into(),
    };
    let php = cligen::php::Php {
        namespace: "Hashinbox".into(),
    };
    let languages = [
        ("typescript/src", cligen::typescript::Typescript.emit(&spec)),
        ("go", go.emit(&spec)),
        ("rust/src", cligen::rust::Rust.emit(&spec)),
        ("python/hashinbox", cligen::python::Python.emit(&spec)),
        ("php/src", php.emit(&spec)),
    ];
    for (dir, files) in languages {
        let dir = root.join("clients").join(dir);
        for path in self::files(&dir) {
            let generated = fs::read_to_string(&path).is_ok_and(|text| {
                let text = text.strip_prefix("<?php\n\n").unwrap_or(&text);
                ["// ", "# "]
                    .iter()
                    .any(|comment| text.starts_with(&format!("{comment}Code generated by cligen")))
            });
            let name = path.strip_prefix(&dir).unwrap();
            if generated && !files.contains_key(name) {
                fs::remove_file(&path)
                    .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
            }
        }
        for (path, text) in files {
            let path = dir.join(path);
            if fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
                fs::write(&path, text)
                    .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
            }
        }
    }
}

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    clients(&root);
    println!("cargo:rustc-env=HASHINBOX_VERSION={}", version(&root));
    let mut rows = Vec::new();
    for (folder, prefix) in [("ui/dist", ""), ("assets", "/assets")] {
        let folder = root.join(folder);
        println!("cargo:rerun-if-changed={}", folder.display());
        for path in files(&folder) {
            let relative = path.strip_prefix(&folder).unwrap().to_str().unwrap();
            let url = format!("{prefix}/{}", relative.replace('\\', "/"));
            rows.push(format!(
                "({url:?}, include_bytes!({:?})),",
                path.display().to_string()
            ));
        }
    }
    rows.sort();
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("files.rs");
    fs::write(out, format!("&[\n{}\n]", rows.join("\n"))).unwrap();
}
